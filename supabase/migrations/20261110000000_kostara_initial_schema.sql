-- SINKRONISASI auth.users -> pengguna
-- =========================================================

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.pengguna (id, email, nomor_telepon, nama_lengkap)
  values (
    new.id,
    coalesce(new.email, ''),
    coalesce(new.phone, new.raw_user_meta_data ->> 'nomor_telepon'),
    coalesce(
      new.raw_user_meta_data ->> 'nama_lengkap',
      new.raw_user_meta_data ->> 'full_name',
      ''
    )
  )
  on conflict (id) do update
    set email = excluded.email,
        diperbarui_pada = now();

  insert into public.profil_pengguna (pengguna_id)
  values (new.id)
  on conflict (pengguna_id) do nothing;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

