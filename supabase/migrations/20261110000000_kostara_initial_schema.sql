create or replace function public.is_kos_member(p_kos_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.anggota_kos a
    where a.kos_id = p_kos_id
      and a.pengguna_id = auth.uid()
      and a.status = 'aktif'
  );
$$;

create or replace function public.is_kos_owner(p_kos_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.kos k
    where k.id = p_kos_id
      and k.pemilik_id = auth.uid()
  ) or exists (
    select 1
    from public.anggota_kos a
    where a.kos_id = p_kos_id
      and a.pengguna_id = auth.uid()
      and a.peran = 'pemilik'
      and a.status = 'aktif'
  );
$$;

create or replace function public.owner_can_view_user(p_pengguna_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.anggota_kos owner
    join public.anggota_kos target on target.kos_id = owner.kos_id
    where owner.pengguna_id = auth.uid()
      and owner.peran = 'pemilik'
      and owner.status = 'aktif'
      and target.pengguna_id = p_pengguna_id
      and target.status = 'aktif'
  );
$$;

