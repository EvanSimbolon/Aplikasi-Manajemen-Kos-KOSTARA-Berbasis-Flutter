create table if not exists public.notifikasi (
  id uuid primary key default gen_random_uuid(),
  penerima_id uuid not null references public.pengguna (id) on delete cascade,
  tagihan_id uuid references public.tagihan (id) on delete cascade,
  jadwal_pemeliharaan_id uuid references public.jadwal_pemeliharaan (id) on delete cascade,
  judul text not null,
  pesan text,
  dijadwalkan_pada timestamptz,
  dikirim_pada timestamptz,
  dibaca_pada timestamptz,
  status text not null default 'menunggu'
    check (status in ('menunggu', 'terkirim', 'dibaca', 'gagal')),
  dibuat_pada timestamptz not null default now()
);

