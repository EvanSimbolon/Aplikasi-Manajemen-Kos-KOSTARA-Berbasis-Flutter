create or replace view public.v_kamar_ketersediaan
with (security_invoker = true)
as
select
  km.id,
  km.kos_id,
  km.nomor_kamar,
  km.tipe_kamar,
  km.harga_sewa_bulanan,
  km.deskripsi,
  not exists (
    select 1
    from public.penyewaan p
    where p.kamar_id = km.id
      and p.status in ('menunggu_mulai', 'aktif')
      and current_date <= p.tanggal_selesai
  ) as tersedia
from public.kamar km;

create or replace view public.v_penghuni_aktif
with (security_invoker = true)
as
select
  p.id as penyewaan_id,
  p.penghuni_id,
  u.nama_lengkap,
  km.id as kamar_id,
  km.nomor_kamar,
  k.id as kos_id,
  k.nama_kos,
  p.tanggal_mulai,
  p.tanggal_selesai,
  p.status as status_penyewaan
from public.penyewaan p
join public.pengguna u on u.id = p.penghuni_id
join public.kamar km on km.id = p.kamar_id
join public.kos k on k.id = km.kos_id
where p.status in ('menunggu_mulai', 'aktif');

create or replace view public.v_riwayat_pembayaran
with (security_invoker = true)
as
select
  pb.id as pembayaran_id,
  p.penghuni_id,
  u.nama_lengkap,
  t.id as tagihan_id,
  t.periode_mulai,
  t.periode_selesai,
  t.jumlah_tagihan,
  pb.jumlah_pembayaran,
  pb.metode_pembayaran,
  pb.dibayar_pada,
  pb.status as status_pembayaran,
  km.nomor_kamar,
  k.nama_kos
from public.pembayaran pb
join public.tagihan t on t.id = pb.tagihan_id
join public.penyewaan p on p.id = t.penyewaan_id
join public.pengguna u on u.id = p.penghuni_id
join public.kamar km on km.id = p.kamar_id
join public.kos k on k.id = km.kos_id;

