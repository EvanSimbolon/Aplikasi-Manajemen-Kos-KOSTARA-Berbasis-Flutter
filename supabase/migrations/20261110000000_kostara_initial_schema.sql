-- KOSTARA initial database schema
-- PostgreSQL / Supabase
--
-- Jalankan file ini melalui Supabase Dashboard -> SQL Editor, atau:
--   supabase db push
--
-- Catatan:
--   - Semua tabel bisnis berada di schema public.
--   - Password tidak disimpan di tabel pengguna; autentikasi ditangani auth.users.
--   - RLS diaktifkan untuk seluruh tabel bisnis.
--   - Policy pada tabel menggunakan helper SECURITY DEFINER untuk menghindari
--     rekursi RLS saat memeriksa keanggotaan kos.

create extension if not exists pgcrypto with schema extensions;
create extension if not exists btree_gist with schema extensions;

set search_path = public, extensions;

-- =========================================================
-- 1. AKUN DAN KEANGGOTAAN
-- =========================================================

create table if not exists public.pengguna (
  id uuid primary key references auth.users (id) on delete cascade,
  email text not null default '',
  nomor_telepon text,
  nama_lengkap text not null default '',
  aktif boolean not null default true,
  dibuat_pada timestamptz not null default now(),
  diperbarui_pada timestamptz not null default now()
);

create table if not exists public.profil_pengguna (
  pengguna_id uuid primary key references public.pengguna (id) on delete cascade,
  foto_url text,
  alamat text,
  dibuat_pada timestamptz not null default now(),
  diperbarui_pada timestamptz not null default now()
);

create table if not exists public.kos (
  id uuid primary key default gen_random_uuid(),
  pemilik_id uuid not null references public.pengguna (id) on delete restrict,
  nama_kos text not null,
  alamat text,
  deskripsi text,
  dibuat_pada timestamptz not null default now(),
  diperbarui_pada timestamptz not null default now()
);

create table if not exists public.anggota_kos (
  id uuid primary key default gen_random_uuid(),
  kos_id uuid not null references public.kos (id) on delete cascade,
  pengguna_id uuid not null references public.pengguna (id) on delete cascade,
  peran text not null check (peran in ('pemilik', 'penghuni')),
  status text not null default 'aktif' check (status in ('aktif', 'nonaktif', 'menunggu')),
  bergabung_pada timestamptz not null default now(),
  unique (kos_id, pengguna_id)
);

create table if not exists public.undangan_penghuni (
  id uuid primary key default gen_random_uuid(),
  kos_id uuid not null references public.kos (id) on delete cascade,
  pengundang_id uuid not null references public.pengguna (id) on delete restrict,
  email_tujuan text not null,
  telepon_tujuan text,
  hash_token text not null unique,
  status text not null default 'menunggu'
    check (status in ('menunggu', 'diterima', 'ditolak', 'kedaluwarsa', 'dibatalkan')),
  berlaku_sampai timestamptz not null,
  diterima_pada timestamptz,
  dibuat_pada timestamptz not null default now()
);

-- =========================================================
-- 2. PENGELOLAAN KOS DAN KAMAR
-- =========================================================

create table if not exists public.kamar (
  id uuid primary key default gen_random_uuid(),
  kos_id uuid not null references public.kos (id) on delete cascade,
  nomor_kamar text not null,
  tipe_kamar text,
  harga_sewa_bulanan numeric(12, 2) not null default 0 check (harga_sewa_bulanan >= 0),
  deskripsi text,
  dibuat_pada timestamptz not null default now(),
  diperbarui_pada timestamptz not null default now(),
  unique (kos_id, nomor_kamar)
);

create table if not exists public.jenis_fasilitas (
  id bigint generated by default as identity primary key,
  nama_fasilitas text not null unique,
  deskripsi text
);

create table if not exists public.fasilitas_kamar (
  id uuid primary key default gen_random_uuid(),
  kamar_id uuid not null references public.kamar (id) on delete cascade,
  jenis_fasilitas_id bigint not null references public.jenis_fasilitas (id) on delete restrict,
  jumlah integer not null default 1 check (jumlah > 0),
  kondisi text not null default 'baik' check (kondisi in ('baik', 'rusak_ringan', 'rusak_berat')),
  tanggal_pemasangan date,
  unique (kamar_id, jenis_fasilitas_id)
);

-- =========================================================
-- 3. PENYEWAAN DAN TAGIHAN
-- =========================================================

create table if not exists public.penyewaan (
  id uuid primary key default gen_random_uuid(),
  kamar_id uuid not null references public.kamar (id) on delete restrict,
  penghuni_id uuid not null references public.pengguna (id) on delete restrict,
  tanggal_mulai date not null,
  tanggal_selesai date not null,
  harga_sewa_disepakati numeric(12, 2) not null check (harga_sewa_disepakati >= 0),
  siklus_tagihan text not null default 'bulanan'
    check (siklus_tagihan in ('bulanan', 'triwulan', 'tahunan')),
  status text not null default 'menunggu_mulai'
    check (status in ('menunggu_mulai', 'aktif', 'berakhir', 'dihentikan')),
  dibuat_pada timestamptz not null default now(),
  check (tanggal_selesai > tanggal_mulai)
);

-- Mencegah dua penyewaan aktif/menunggu pada kamar yang sama dalam periode
-- yang bertabrakan. Perpanjangan harus dibuat sebagai baris baru.
alter table public.penyewaan
  drop constraint if exists penyewaan_kamar_tidak_tumpang_tindih;
alter table public.penyewaan
  add constraint penyewaan_kamar_tidak_tumpang_tindih
  exclude using gist (
    kamar_id with =,
    daterange(tanggal_mulai, tanggal_selesai, '[)') with &&
  ) where (status in ('menunggu_mulai', 'aktif'));

create table if not exists public.tagihan (
  id uuid primary key default gen_random_uuid(),
  penyewaan_id uuid not null references public.penyewaan (id) on delete cascade,
  periode_mulai date not null,
  periode_selesai date not null,
  diterbitkan_pada timestamptz not null default now(),
  tanggal_jatuh_tempo date not null,
  jumlah_tagihan numeric(12, 2) not null check (jumlah_tagihan >= 0),
  status text not null default 'belum_bayar'
    check (status in ('belum_bayar', 'terlambat', 'dibayar_sebagian', 'lunas', 'dibatalkan')),
  unique (penyewaan_id, periode_mulai, periode_selesai),
  check (periode_selesai > periode_mulai)
);

-- =========================================================
-- 4. PEMBAYARAN
-- =========================================================

create table if not exists public.pembayaran (
  id uuid primary key default gen_random_uuid(),
  tagihan_id uuid not null references public.tagihan (id) on delete restrict,
  pembayar_id uuid not null references public.pengguna (id) on delete restrict,
  jumlah_pembayaran numeric(12, 2) not null check (jumlah_pembayaran > 0),
  metode_pembayaran text,
  dibayar_pada timestamptz not null default now(),
  status text not null default 'menunggu_verifikasi'
    check (status in ('menunggu_verifikasi', 'terverifikasi', 'ditolak')),
  pemeriksa_id uuid references public.pengguna (id) on delete set null,
  diperiksa_pada timestamptz,
  catatan text,
  dibuat_pada timestamptz not null default now()
);

create table if not exists public.bukti_pembayaran (
  id uuid primary key default gen_random_uuid(),
  pembayaran_id uuid not null references public.pembayaran (id) on delete cascade,
  lokasi_berkas text not null,
  diunggah_pada timestamptz not null default now()
);

-- =========================================================
-- 5. FASILITAS DAN PEMELIHARAAN
-- =========================================================

create table if not exists public.laporan_kerusakan (
  id uuid primary key default gen_random_uuid(),
  fasilitas_kamar_id uuid not null references public.fasilitas_kamar (id) on delete restrict,
  pelapor_id uuid not null references public.pengguna (id) on delete restrict,
  judul text not null,
  deskripsi text,
  dilaporkan_pada timestamptz not null default now(),
  status text not null default 'dilaporkan'
    check (status in ('dilaporkan', 'diproses', 'selesai', 'ditolak')),
  diselesaikan_pada timestamptz
);

create table if not exists public.jadwal_pemeliharaan (
  id uuid primary key default gen_random_uuid(),
  fasilitas_kamar_id uuid not null references public.fasilitas_kamar (id) on delete restrict,
  pembuat_jadwal_id uuid not null references public.pengguna (id) on delete restrict,
  jadwal_pada timestamptz not null,
  jenis_pemeliharaan text not null,
  deskripsi text,
  status text not null default 'dijadwalkan'
    check (status in ('dijadwalkan', 'diproses', 'selesai', 'dibatalkan')),
  selesai_pada timestamptz
);

-- =========================================================
-- 6. KALENDER
-- =========================================================

create table if not exists public.acara_kalender (
  id uuid primary key default gen_random_uuid(),
  kos_id uuid not null references public.kos (id) on delete cascade,
  pembuat_id uuid not null references public.pengguna (id) on delete restrict,
  judul text not null,
  deskripsi text,
  mulai_pada timestamptz not null,
  selesai_pada timestamptz,
  jenis_acara text,
  visibilitas text not null default 'anggota'
    check (visibilitas in ('publik', 'anggota', 'pribadi')),
  dibuat_pada timestamptz not null default now(),
  check (selesai_pada is null or selesai_pada >= mulai_pada)
);

-- =========================================================
-- 7. NOTIFIKASI
